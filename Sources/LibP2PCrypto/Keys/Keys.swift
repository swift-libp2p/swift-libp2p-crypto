import Crypto
import Foundation
import Multibase
import SwiftProtobuf

extension LibP2PCrypto {
    public enum Keys {

        public enum KeyType: Sendable, Hashable, CaseIterable, CustomStringConvertible {
            case rsa
            case ed25519
            case secp256k1
            case ecdsa

            public var description: String {
                switch self {
                case .rsa: return "RSA"
                case .ed25519: return "Ed25519"
                case .secp256k1: return "Secp256k1"
                case .ecdsa: return "ECDSA"
                }
            }

            /// The equivalent protobuf `KeyType` used when marshaling keys
            internal var protoType: ProtoKeyType {
                switch self {
                case .rsa: return .rsa
                case .ed25519: return .ed25519
                case .secp256k1: return .secp256K1
                case .ecdsa: return .ecdsa
                }
            }

            internal init(_ protoType: ProtoKeyType) {
                switch protoType {
                case .rsa: self = .rsa
                case .ed25519: self = .ed25519
                case .secp256K1: self = .secp256k1
                case .ecdsa: self = .ecdsa
                }
            }
        }

        /// The NIST elliptic curves supported for ECDSA keys
        public enum EllipticCurve: Sendable, Hashable, CaseIterable, CustomStringConvertible {
            case p256
            case p384
            case p521

            /// The curve's size in bits
            public var bits: Int {
                switch self {
                case .p256: return 256
                case .p384: return 384
                case .p521: return 521
                }
            }

            public var description: String {
                "P-\(bits)"
            }
        }

        /// The RSA modulus size
        ///
        /// - Note: RSA keys must be between 2048 and 8192 bits (``supportedBitRange``),
        ///   matching swift-crypto and go-libp2p's limits.
        public enum RSABitLength: Sendable, Hashable, CustomStringConvertible {

            /// The range of RSA key sizes (in bits) that we accept
            public static let supportedBitRange: ClosedRange<Int> = 2048...8192

            case b2048
            case b3072
            case b4096
            /// - Note: Generating 8192 bit keys can take a few seconds
            case b8192
            /// - Note: Must be within ``supportedBitRange``
            case custom(bits: Int)

            /// The modulus size in bits
            public var bits: Int {
                switch self {
                case .b2048: return 2048
                case .b3072: return 3072
                case .b4096: return 4096
                case .b8192: return 8192
                case .custom(let bits): return bits
                }
            }

            public var description: String {
                "\(self.bits) bit"
            }
        }

        /// The parameters used to generate a new ``KeyPair``
        public enum KeyPairType: Sendable, Hashable, CustomStringConvertible {
            case rsa(bits: RSABitLength = .b2048)
            case ed25519
            case secp256k1
            case ecdsa(curve: EllipticCurve = .p256)

            /// The type of key generated by this specification
            public var keyType: KeyType {
                switch self {
                case .rsa: return .rsa
                case .ed25519: return .ed25519
                case .secp256k1: return .secp256k1
                case .ecdsa: return .ecdsa
                }
            }

            public var description: String {
                switch self {
                case .rsa(let bits): return "RSA (\(bits))"
                case .ed25519: return "Ed25519"
                case .secp256k1: return "Secp256k1"
                case .ecdsa(let curve): return "ECDSA (\(curve))"
                }
            }
        }

        public static func generateKeyPair(_ type: KeyPairType) throws -> KeyPair {
            try LibP2PCrypto.Keys.KeyPair(type)
        }

        /// Asynchronously generates a new key pair off the calling thread.
        ///
        /// Prefer this over the synchronous initializer for large RSA keys (3072+ bit),
        /// where generation can take a noticeable amount of time and would otherwise block the
        /// current task/actor.
        public static func generateKeyPair(_ type: KeyPairType) async throws -> KeyPair {
            try await Task.detached(priority: .userInitiated) {
                try LibP2PCrypto.Keys.KeyPair(type)
            }.value
        }

        /// Converts a protobuf serialized public key into its base encoded key data
        /// (for every key type this is the protobuf's `Data` field, ex: the DER encoded SubjectPublicKeyInfo for RSA keys).
        public static func unmarshalPublicKey(buf: [UInt8], into base: BaseEncoding = .base16) throws -> String {
            let pubKeyProto = try ProtoPublicKey(serializedBytes: buf)

            guard !pubKeyProto.data.isEmpty else {
                throw KeyError.invalidMarshaledData("Public key payload was empty")
            }

            return pubKeyProto.data.asString(base: base)
        }

        /// Converts a base encoded raw private key string into a protobuf serialized private key.
        public static func marshalPrivateKey(
            raw: String,
            keyType: KeyType,
            fromBase base: BaseEncoding? = nil
        ) throws -> [UInt8] {
            let decoded: [UInt8]
            do {
                if let b = base {
                    decoded = try BaseEncoding.decode(raw, as: b)
                } else {
                    decoded = try BaseEncoding.decode(raw).bytes
                }
            } catch {
                throw KeyError.invalidParameters(
                    "Failed to decode raw private key, unknown base encoding: \(error)"
                )
            }
            return try self.marshalPrivateKey(raw: Data(decoded), keyType: keyType)
        }

        /// Converts a raw private key into a protobuf serialized private key.
        public static func marshalPrivateKey(raw: Data, keyType: KeyType) throws -> [UInt8] {
            var privKeyProto = ProtoPrivateKey()
            privKeyProto.data = raw
            privKeyProto.type = keyType.protoType
            return Array(try privKeyProto.serializedData())
        }

        /// Converts a protobuf serialized private key into its base encoded key data.
        public static func unmarshalPrivateKey(buf: [UInt8], into base: BaseEncoding = .base16) throws -> String {
            let privKeyProto = try ProtoPrivateKey(serializedBytes: buf)

            let data = privKeyProto.data
            guard !data.isEmpty else { throw KeyError.invalidMarshaledData("Private key payload was empty") }

            return data.asString(base: base)
        }
    }
}
